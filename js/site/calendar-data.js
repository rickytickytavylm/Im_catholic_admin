  var WEEKDAY_SHORT = {
    'Понедельник': 'пн',
    'Вторник': 'вт',
    'Среда': 'ср',
    'Четверг': 'чт',
    'Пятница': 'пт',
    'Суббота': 'сб',
    'Воскресенье': 'вскр'
  };

  function todayIso() {
    var d = new Date();
    return d.getFullYear() + '-' + String(d.getMonth() + 1).padStart(2, '0') + '-' + String(d.getDate()).padStart(2, '0');
  }

  function byDate(iso) {
    for (var i = 0; i < DAYS.length; i++) if (DAYS[i].date === iso) return DAYS[i];
    return null;
  }

  /** Ровно 7 дней одним окном, начиная с iso (или с ближайшего доступного). */
  function weekFrom(iso) {
    var start = iso || todayIso();
    var idx = DAYS.findIndex(function (d) { return d.date === start; });
    if (idx < 0) {
      idx = DAYS.findIndex(function (d) { return d.date >= start; });
      if (idx < 0) idx = Math.max(0, DAYS.length - 7);
    }
    if (idx > DAYS.length - 7) idx = Math.max(0, DAYS.length - 7);
    return DAYS.slice(idx, idx + 7);
  }

  function weekdayShort(weekday) {
    return WEEKDAY_SHORT[weekday] || String(weekday || '').slice(0, 2).toLowerCase();
  }

  function upcomingEvents(fromIso) {
    if (global.YakAfisha) return global.YakAfisha.upcomingEvents(fromIso);
    return [];
  }

  function eventsOn(iso) {
    if (global.YakAfisha) return global.YakAfisha.eventsOn(iso);
    return [];
  }

